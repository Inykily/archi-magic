# -*- coding: utf-8 -*-
"""Tests for scripts/lib/side_effects.py (issue #28).

Run either way:
    python -m pytest skills/am-safe-change/tests -q
    python skills/am-safe-change/tests/test_side_effects.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "scripts", "lib"))

import side_effects as se  # noqa: E402


def preview(steps=10, expected=None):
    return {"kind": "change-preview", "steps": [{"id": i} for i in range(steps)],
            "expected_dependent_categories": expected or []}


def dryrun(modified=1143, by_category=None):
    return {"modified_count": modified,
            "modified_by_category": by_category or {}}


def test_issue_example_ten_materials():
    # The issue #28 example: 10 materials, 1143 changed in total.
    s = se.summarize(preview(10, ["Floors", "Keynote Tags", "Legends"]),
                     dryrun(1143, {"Materials": 10, "Floors": 292,
                                   "Keynote Tags": 831, "Legends": 10}),
                     ["Materials"])
    assert s["available"] is True
    assert s["edited"] == 10
    assert s["modified_count"] == 1143
    assert s["regenerated"] == 1133
    assert s["unexpected"] == []
    assert s["warnings"] == []
    kinds = dict((cat, kind) for cat, _n, kind in s["by_category"])
    assert kinds == {"Materials": "edited", "Floors": "expected",
                     "Keynote Tags": "expected", "Legends": "expected"}
    assert "Floors" in s["explanation"]


def test_unexpected_category_warns():
    s = se.summarize(preview(10, ["Floors"]),
                     dryrun(15, {"Materials": 10, "Floors": 2, "Walls": 3}),
                     ["Materials"])
    assert s["regenerated"] == 5
    assert s["unexpected"] == ["Walls"]
    assert len(s["warnings"]) == 1
    assert "Walls" in s["warnings"][0]
    table = se.text_table(s)
    assert "Edited on purpose: 10." in table
    assert "Regenerated by Revit: 5 of 15 changed in total." in table
    assert "Walls 3 (unexpected)" in table


def test_no_dependents():
    s = se.summarize(preview(7, ["Views"]),
                     dryrun(7, {"Sheets": 7}), ["Sheets"])
    assert s["regenerated"] == 0
    assert s["explanation"] == "No dependent elements changed."


def test_missing_modified_count():
    s = se.summarize(preview(3), {"rows": []}, ["Sheets"])
    assert s["available"] is False
    assert "no modified_count" in se.text_table(s)


def test_dryrun_inside_envelope():
    s = se.summarize(preview(2, ["Views"]),
                     {"result": dryrun(5, {"Sheets": 2, "Views": 3})},
                     ["Sheets"])
    assert s["available"] is True
    assert s["regenerated"] == 3


def test_fewer_changed_than_steps():
    s = se.summarize(preview(5), dryrun(3, {"Sheets": 3}), ["Sheets"])
    assert s["regenerated"] == 0
    assert any("fewer" in w for w in s["warnings"])


if __name__ == "__main__":
    import pytest
    sys.exit(pytest.main([__file__, "-q"]))
